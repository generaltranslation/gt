import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { resolvePackage } from '../utils/resolve-package.js';
import { virtualModulePrefix } from './virtual-modules.js';

export type OutdirVerdict =
  | { outdir: true }
  /** `reason` is set when the directory has Paraglide's files but they do not verify. */
  | { outdir: false; reason?: string };

export type OutdirDetectorOptions = {
  /**
   * Where else to look for `@inlang/paraglide-js` when it cannot be resolved
   * from the outdir, e.g. the project and workspace roots.
   */
  fallbackDirectories?: readonly string[];
};

/** What an installed `@inlang/paraglide-js` generates, or why it cannot be known. */
type Paraglide =
  /** Paraglide 2 and 3: files that do not depend on the project. */
  | ExactParaglide
  /** Paraglide 1: every file depends on the project, so the output's structure is checked. */
  | { type: 'structure'; version: string }
  | { type: 'unknown'; version: string; reason: string };

type ExactParaglide = {
  type: 'exact';
  version: string;
  registry: string;
  barrel: string;
};

type OutdirFiles = {
  messages: string;
  runtime: string;
  registry: string | undefined;
  server: string | undefined;
};

/** Generated files by name, e.g. "registry.js". */
type Output = Record<string, string>;

type CompileProject = (args: { project: unknown }) => Promise<Output>;

/** The compilers of `@inlang/paraglide-js`: Paraglide 3 has the first, Paraglide 2 the second. */
type ParaglideModule = {
  compileCatalog?: (args: { catalog: unknown }) => Promise<Output>;
  compileProject?: CompileProject;
};

/**
 * No locale in particular ("undetermined"): an empty catalog is compiled only
 * for its `registry.js` and `messages.js`, which name no locale.
 */
const EMPTY_CATALOG_LOCALE = 'und';
const EMPTY_CATALOG_SETTINGS = {
  baseLocale: EMPTY_CATALOG_LOCALE,
  locales: [EMPTY_CATALOG_LOCALE],
};

const ESLINT_DISABLE = '/* eslint-disable */';

// `includeEslintDisableComment` adds one of these lines; they carry no meaning.
const ESLINT_LINES = new Set([ESLINT_DISABLE, '// eslint-disable']);

// Written by Paraglide's Vite plugin above `messages.js` in virtual-modules mode.
const VIRTUAL_HEADER =
  '// Generated by Paraglide. Message implementations are virtual modules.\n' +
  '// The Paraglide Vite plugin supplies them in development and production builds.\n';

/** In Paraglide 1's `runtime.js`; the group is the JSON list of tags. */
const AVAILABLE_LANGUAGE_TAGS =
  /^export const availableLanguageTags = \/\*\* @type \{const\} \*\/ \((\[.*\])\)$/m;

/**
 * Decides whether a directory is a Paraglide outdir by comparing its files with
 * what the `@inlang/paraglide-js` installed for that directory generates.
 */
export class OutdirDetector {
  private readonly verdicts = new Map<string, Promise<OutdirVerdict>>();
  private readonly paraglides = new Map<string, Promise<Paraglide>>();

  constructor(private readonly options: OutdirDetectorOptions = {}) {}

  check(directory: string): Promise<OutdirVerdict> {
    let verdict = this.verdicts.get(directory);

    if (!verdict) {
      verdict = this.verify(directory);
      this.verdicts.set(directory, verdict);
    }

    return verdict;
  }

  clear(): void {
    this.verdicts.clear();
  }

  private async verify(directory: string): Promise<OutdirVerdict> {
    const files = await readOutdirFiles(directory);
    if (!files) return { outdir: false };

    const paraglides = await this.paraglidesFor(directory);
    if (paraglides.length === 0) {
      return {
        outdir: false,
        reason:
          '@inlang/paraglide-js cannot be resolved from it or from the project',
      };
    }

    const reasons: string[] = [];

    for (const paraglide of paraglides) {
      const mismatch = await mismatchWith(paraglide, files, directory);
      if (mismatch === undefined) return { outdir: true };

      reasons.push(mismatch);
    }

    return { outdir: false, reason: reasons.join('; ') };
  }

  /** Each distinct installed Paraglide that the outdir or a fallback directory resolves. */
  private async paraglidesFor(directory: string): Promise<Paraglide[]> {
    const { fallbackDirectories = [] } = this.options;
    const entries = new Set<string>();

    for (const from of [directory, ...fallbackDirectories]) {
      const entry = await resolvePackage(from, '@inlang/paraglide-js');
      if (entry) entries.add(entry);
    }

    return Promise.all([...entries].map((entry) => this.paraglideAt(entry)));
  }

  /** What the Paraglide whose entry file is `entry` generates, found out once. */
  private paraglideAt(entry: string): Promise<Paraglide> {
    let paraglide = this.paraglides.get(entry);

    if (!paraglide) {
      paraglide = generate(entry).catch(
        (error: Error): Paraglide => ({
          type: 'unknown',
          version: '?',
          reason: `@inlang/paraglide-js could not generate files to verify against: ${error.message}`,
        })
      );
      this.paraglides.set(entry, paraglide);
    }

    return paraglide;
  }
}

/** The directory's generated files; undefined without the two that every Paraglide version writes. */
async function readOutdirFiles(
  directory: string
): Promise<OutdirFiles | undefined> {
  const read = (file: string) =>
    fs.readFile(path.join(directory, file), 'utf8').catch(() => undefined);

  const [messages, runtime, registry, server] = await Promise.all(
    ['messages.js', 'runtime.js', 'registry.js', 'server.js'].map(read)
  );
  if (messages === undefined || runtime === undefined) return undefined;

  return { messages, runtime, registry, server };
}

/** Why `files` were not generated by `paraglide`; undefined if they were. */
async function mismatchWith(
  paraglide: Paraglide,
  files: OutdirFiles,
  directory: string
): Promise<string | undefined> {
  switch (paraglide.type) {
    case 'unknown':
      return paraglide.reason;

    case 'structure': {
      const isOutput = await isParaglide1Output(files, directory);

      return isOutput
        ? undefined
        : `its files were not generated by ${nameOf(paraglide)}`;
    }

    case 'exact':
      return exactMismatch(paraglide, files, directory);
  }
}

function exactMismatch(
  paraglide: ExactParaglide,
  files: OutdirFiles,
  directory: string
): string | undefined {
  const generatedBy = nameOf(paraglide);

  if (files.registry === undefined || files.server === undefined) {
    return `registry.js or server.js is missing, which ${generatedBy} generates`;
  }

  const isSameRegistry =
    withoutEslintLine(files.registry) === paraglide.registry;
  if (!isSameRegistry) {
    return `registry.js was not generated by ${generatedBy}`;
  }

  const barrel = withoutEslintLine(files.messages);
  const isSameBarrel =
    barrel === paraglide.barrel ||
    barrel === virtualBarrel(paraglide.barrel, directory);
  if (!isSameBarrel) {
    return `messages.js was not generated by ${generatedBy} for this directory`;
  }

  return undefined;
}

/** The `messages.js` of virtual-modules mode: it imports the message modules by their virtual id. */
function virtualBarrel(barrel: string, directory: string): string {
  const virtualIndex = `${virtualModulePrefix(directory)}messages/_index.js`;

  return (
    VIRTUAL_HEADER +
    barrel.replaceAll("'./messages/_index.js'", JSON.stringify(virtualIndex))
  );
}

function nameOf(paraglide: Paraglide): string {
  return `@inlang/paraglide-js ${paraglide.version}`;
}

/** What the Paraglide whose entry file is `entry` generates for a project without messages. */
async function generate(entry: string): Promise<Paraglide> {
  const version = await packageVersion(entry);
  const major = Number(version.split('.')[0]);
  if (major === 1) return { type: 'structure', version };

  const module: ParaglideModule = await import(pathToFileURL(entry).href);
  const output = await compileEmpty(module, entry);

  if (!output) {
    return {
      type: 'unknown',
      version,
      reason: `@inlang/paraglide-js ${version} has neither compileCatalog() nor compileProject() to verify against`,
    };
  }

  return {
    type: 'exact',
    version,
    registry: withoutEslintLine(output['registry.js']!),
    barrel: withoutEslintLine(output['messages.js']!),
  };
}

/** undefined if the module has no compiler this knows. */
async function compileEmpty(
  module: ParaglideModule,
  entry: string
): Promise<Output | undefined> {
  // Paraglide 3
  if (typeof module.compileCatalog === 'function') {
    return module.compileCatalog({
      catalog: { settings: EMPTY_CATALOG_SETTINGS, bundles: [] },
    });
  }

  // Paraglide 2 compiles an SDK project; an empty one in memory suffices.
  if (typeof module.compileProject === 'function') {
    return compileEmptyProject(entry, module.compileProject);
  }

  return undefined;
}

async function compileEmptyProject(
  entry: string,
  compileProject: CompileProject
): Promise<Output> {
  // The SDK that this Paraglide was installed with.
  const sdkEntry = await resolvePackage(path.dirname(entry), '@inlang/sdk');
  if (!sdkEntry) throw new Error('@inlang/sdk is not installed next to it');

  const sdk = await import(pathToFileURL(sdkEntry).href);
  const blob = await sdk.newProject({
    // `telemetry: "off"` keeps older SDKs from reporting the loaded project.
    settings: { ...EMPTY_CATALOG_SETTINGS, telemetry: 'off' },
  });
  const project = await sdk.loadProjectInMemory({ blob });

  try {
    return await compileProject({ project });
  } finally {
    await project.close?.();
  }
}

/**
 * Paraglide 1 writes `runtime.js` from a fixed template, and `messages.js` that
 * imports either one module per locale or one module per message.
 */
async function isParaglide1Output(
  files: OutdirFiles,
  directory: string
): Promise<boolean> {
  const languageTags = paraglide1LanguageTags(files.runtime);
  if (!languageTags || !isParaglide1Barrel(files.messages)) return false;

  const localeFiles = await Promise.all(
    languageTags.map((tag) =>
      isParaglide1Module(path.join(directory, 'messages', `${tag}.js`))
    )
  );

  return localeFiles.every(Boolean);
}

/** The language tags of a `runtime.js` written from Paraglide 1's template; undefined for any other. */
function paraglide1LanguageTags(runtimeFile: string): string[] | undefined {
  const runtime = withoutEslintLine(runtimeFile);
  const isFromTemplate =
    runtime.includes('\nexport const sourceLanguageTag = ') &&
    runtime.includes('\nexport let languageTag = () => sourceLanguageTag\n');
  const tags = AVAILABLE_LANGUAGE_TAGS.exec(runtime)?.[1];
  if (!isFromTemplate || tags === undefined) return undefined;

  let languageTags: unknown;
  try {
    languageTags = JSON.parse(tags);
  } catch {
    return undefined;
  }

  const areTags =
    Array.isArray(languageTags) &&
    languageTags.every((tag) => typeof tag === 'string');

  return areTags ? (languageTags as string[]) : undefined;
}

/** A `messages.js` that re-exports one module per message, or imports one per locale. */
function isParaglide1Barrel(messages: string): boolean {
  if (!messages.startsWith(ESLINT_DISABLE)) return false;

  const body = messages.slice(ESLINT_DISABLE.length);
  const isPerMessage =
    body === '' || body.startsWith('\nexport * from "./messages/index/');
  const isPerLocale = body.startsWith(
    '\nimport { languageTag } from "./runtime.js"'
  );

  return isPerMessage || isPerLocale;
}

function isParaglide1Module(file: string): Promise<boolean> {
  return fs
    .readFile(file, 'utf8')
    .then((code) => code.startsWith(ESLINT_DISABLE))
    .catch(() => false);
}

/** The version in the package.json of `@inlang/paraglide-js`, at or above its entry file; "?" if unknown. */
async function packageVersion(entry: string): Promise<string> {
  for (
    let directory = path.dirname(entry);
    ;
    directory = path.dirname(directory)
  ) {
    const manifest = await fs
      .readFile(path.join(directory, 'package.json'), 'utf8')
      .then((json) => JSON.parse(json) as { name?: string; version?: string })
      .catch(() => undefined);

    if (manifest?.name === '@inlang/paraglide-js')
      return manifest.version ?? '?';

    const isFilesystemRoot = path.dirname(directory) === directory;
    if (isFilesystemRoot) return '?';
  }
}

function withoutEslintLine(code: string): string {
  return code
    .split('\n')
    .filter((line) => !ESLINT_LINES.has(line))
    .join('\n');
}

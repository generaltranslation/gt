import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import os from 'node:os';
import path from 'node:path';
import { afterAll, describe, expect, test } from 'vitest';
import { compileCatalog } from '@inlang/paraglide-js';
import { OutdirDetector } from '../../lib/compiler/paraglide/outdir.js';

// Inside the package, so `@inlang/paraglide-js` resolves from the outdirs.
const TMP = path.join(import.meta.dirname, '.tmp', 'outdir');

afterAll(() => fs.rm(TMP, { recursive: true, force: true }));

const greeting = {
  id: 'greeting',
  declarations: [],
  messages: ['en', 'de'].map((locale) => ({
    id: `greeting_${locale}`,
    bundleId: 'greeting',
    locale,
    selectors: [],
    variants: [
      {
        id: `greeting_${locale}_v`,
        messageId: `greeting_${locale}`,
        matches: [],
        pattern: [{ type: 'text', value: locale === 'en' ? 'Hi' : 'Hallo' }],
      },
    ],
  })),
};

type Output = Record<string, string>;

function compileOutput(
  compilerOptions: Parameters<typeof compileCatalog>[0]['compilerOptions'] = {}
): Promise<Output> {
  return compileCatalog({
    catalog: {
      settings: { baseLocale: 'en', locales: ['en', 'de'] },
      bundles: [greeting],
    } as never,
    compilerOptions,
  });
}

async function write(directory: string, output: Output): Promise<string> {
  for (const [file, content] of Object.entries(output)) {
    await fs.mkdir(path.dirname(path.join(directory, file)), {
      recursive: true,
    });
    await fs.writeFile(path.join(directory, file), content);
  }
  return directory;
}

let count = 0;
const fresh = () => path.join(TMP, `outdir-${count++}`);

/** What Paraglide's Vite plugin writes for `directory` in virtual-modules mode. */
function virtualOutput(output: Output, directory: string): Output {
  const hash = createHash('sha256')
    .update(path.resolve(directory))
    .digest('hex');
  const id = `virtual:paraglide/${hash.slice(0, 16)}/messages/_index.js`;
  const disk = Object.fromEntries(
    Object.entries(output).filter(([file]) => !file.startsWith('messages/'))
  );
  disk['messages.js'] =
    '// Generated by Paraglide. Message implementations are virtual modules.\n' +
    '// The Paraglide Vite plugin supplies them in development and production builds.\n' +
    output['messages.js']!.replaceAll(
      "'./messages/_index.js'",
      JSON.stringify(id)
    );
  return disk;
}

const check = (directory: string) => new OutdirDetector().check(directory);

describe('detects Paraglide outdirs', () => {
  test.each([
    ['message-modules', {}],
    ['locale-modules', { outputStructure: 'locale-modules' as const }],
    ['sharded message-modules', { messageModuleSize: 2 }],
    ['without eslint comments', { includeEslintDisableComment: false }],
  ])('%s', async (_name, options) => {
    const directory = await write(fresh(), await compileOutput(options));
    expect(await check(directory)).toEqual({ outdir: true });
  });

  test('virtual-modules output for its own directory', async () => {
    const directory = fresh();
    await write(directory, virtualOutput(await compileOutput(), directory));
    expect(await check(directory)).toEqual({ outdir: true });
  });
});

describe('rejects everything else', () => {
  test('virtual-modules output copied from another directory', async () => {
    const directory = await write(
      fresh(),
      virtualOutput(await compileOutput(), '/somewhere/else')
    );
    expect(await check(directory)).toMatchObject({
      outdir: false,
      reason: expect.stringContaining('messages.js'),
    });
  });

  test('output of another Paraglide version', async () => {
    const output = await compileOutput();
    output['registry.js'] = output['registry.js']!.replace('plural', 'plurals');
    const directory = await write(fresh(), output);
    expect(await check(directory)).toMatchObject({
      outdir: false,
      reason: expect.stringContaining('registry.js'),
    });
  });

  test('a hand-written directory with the same file names', async () => {
    const directory = await write(fresh(), {
      'messages.js': "export * from './messages/_index.js'",
      'runtime.js': "export const getLocale = () => 'en'",
      'server.js': 'export {}',
      'registry.js': 'export {}',
    });
    expect(await check(directory)).toMatchObject({ outdir: false });
  });

  test('app code that only has a messages.js, silently', async () => {
    const directory = await write(fresh(), { 'messages.js': 'export {}' });
    expect(await check(directory)).toEqual({ outdir: false });
  });

  test('output where @inlang/paraglide-js cannot be resolved', async () => {
    const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'outdir-'));
    await write(directory, await compileOutput());
    expect(await check(directory)).toMatchObject({
      outdir: false,
      reason: expect.stringContaining('cannot be resolved'),
    });
    await fs.rm(directory, { recursive: true, force: true });
  });
});

describe('other installs of @inlang/paraglide-js', () => {
  test("falls back to the project's install when the outdir cannot resolve it", async () => {
    const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'outdir-'));
    await write(directory, await compileOutput());
    const detector = new OutdirDetector({
      fallbackDirectories: [import.meta.dirname],
    });
    expect(await detector.check(directory)).toEqual({ outdir: true });
    await fs.rm(directory, { recursive: true, force: true });
  });

  /** A directory whose `@inlang/paraglide-js` is the package installed as `alias`. */
  async function withParaglide(
    alias: string
  ): Promise<{ root: string; module: any; sdk: any }> {
    const root = fresh();
    const installed = await fs.realpath(
      path.join(import.meta.dirname, '../../node_modules', alias)
    );
    await fs.mkdir(path.join(root, 'node_modules/@inlang'), {
      recursive: true,
    });
    await fs.symlink(
      installed,
      path.join(root, 'node_modules/@inlang/paraglide-js')
    );
    const module = await import(alias);
    const sdk = await import(
      createRequire(path.join(installed, '_.js')).resolve('@inlang/sdk')
    ).catch(() => undefined);
    return { root, module, sdk };
  }

  test.each([['message-modules'], ['locale-modules']] as const)(
    'Paraglide 2 (%s)',
    async (outputStructure) => {
      const { root, module, sdk } = await withParaglide('paraglide-js-2');
      const blob = await sdk.newProject({
        settings: { baseLocale: 'en', locales: ['en', 'de'], telemetry: 'off' },
      });
      const project = await sdk.loadProjectInMemory({ blob });
      const output = await module.compileProject({
        project,
        compilerOptions: { outputStructure },
      });
      await project.close();
      const directory = await write(path.join(root, 'src/paraglide'), output);
      expect(await check(directory)).toEqual({ outdir: true });

      await fs.appendFile(
        path.join(directory, 'registry.js'),
        '\nexport const x = 1;\n'
      );
      expect(await check(directory)).toMatchObject({
        outdir: false,
        reason: expect.stringMatching(
          /registry\.js was not generated by @inlang\/paraglide-js 2\./
        ),
      });
    },
    60_000
  );

  /** Paraglide 1's output; its compiler sends telemetry, so the files are written here. */
  function paraglide1Output(tags: string[]): Output {
    const runtime = [
      '// eslint-disable',
      '',
      '/** @type {((tag: AvailableLanguageTag) => void) | undefined} */',
      'let _onSetLanguageTag',
      '',
      `export const sourceLanguageTag = "${tags[0]}"`,
      '',
      `export const availableLanguageTags = /** @type {const} */ (${JSON.stringify(tags)})`,
      '',
      'export let languageTag = () => sourceLanguageTag',
      '',
    ].join('\n');
    return {
      'runtime.js': runtime,
      'messages.js': [
        '/* eslint-disable */',
        'import { languageTag } from "./runtime.js"',
        tags
          .map((tag) => `import * as ${tag} from "./messages/${tag}.js"`)
          .join('\n'),
        '',
        'export const greeting = () => en.greeting()',
      ].join('\n'),
      ...Object.fromEntries(
        tags.map((tag) => [
          `messages/${tag}.js`,
          `/* eslint-disable */\nexport const greeting = () => "Hi"`,
        ])
      ),
    };
  }

  test('Paraglide 1', async () => {
    const { root } = await withParaglide('paraglide-js-1');
    const directory = await write(
      path.join(root, 'src/paraglide'),
      paraglide1Output(['en', 'de'])
    );
    expect(await check(directory)).toEqual({ outdir: true });

    await fs.rm(path.join(directory, 'messages/de.js'));
    expect(await check(directory)).toMatchObject({
      outdir: false,
      reason: expect.stringContaining(
        'were not generated by @inlang/paraglide-js 1.'
      ),
    });
  });

  test('Paraglide 1 output with Paraglide 3 installed', async () => {
    const directory = await write(fresh(), paraglide1Output(['en']));
    expect(await check(directory)).toMatchObject({
      outdir: false,
      reason: expect.stringContaining('registry.js or server.js is missing'),
    });
  });
});

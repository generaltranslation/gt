const TRANSFORMABLE_EXTENSIONS = ['.tsx', '.jsx', '.ts', '.js'];

/**
 * Query keys that turn a JS/TS file import into something other than the
 * module's own source (a string, a URL, a worker wrapper, ...).
 * Other queries (e.g. TanStack's `?tsr-split=component`) still carry source.
 */
const NON_SOURCE_QUERY_KEYS = new Set([
  'raw',
  'url',
  'worker',
  'sharedworker',
  'inline',
  'import',
]);

function splitModuleId(id: string): { path: string; queryKeys: string[] } {
  const queryIndex = id.search(/[?#]/);
  if (queryIndex === -1) return { path: id, queryKeys: [] };
  const query = id.slice(queryIndex + 1).split('#')[0];
  return {
    path: id.slice(0, queryIndex),
    queryKeys: query.split('&').map((param) => param.split('=')[0]),
  };
}

/**
 * Whether the compiler should transform the module with this id.
 */
export function shouldTransformModuleId(id: string): boolean {
  // Rollup/Vite virtual modules (`\0` prefix) are generated by other plugins
  if (id.startsWith('\0')) return false;
  const { path, queryKeys } = splitModuleId(id);
  // Dependencies ship compiled code; transforming them breaks some builds
  if (/[\\/]node_modules[\\/]/.test(path)) return false;
  if (path.endsWith('.d.ts')) return false;
  if (queryKeys.some((key) => NON_SOURCE_QUERY_KEYS.has(key))) return false;
  return TRANSFORMABLE_EXTENSIONS.some((extension) => path.endsWith(extension));
}

/**
 * Diagnostics for the locale twins build integration (prerequisites, output
 * checks and the server manifest module).
 */
import {
  createCompilerDiagnostic,
  formatDiagnosticErrorDetails,
} from '../utils/diagnostics';

function errorDetails(label: string, error: unknown): string[] {
  const details = formatDiagnosticErrorDetails(error);
  return details === undefined ? [label] : [label, details];
}

/**
 * Translation files are missing, so the twins of those locales render the
 * source text. `missingFiles` is `undefined` when `files.gt.output` is not set.
 */
export function createMissingTranslationFilesDiagnostic(
  missingFiles: string[] | undefined
): string {
  const notConfigured = missingFiles === undefined;
  return createCompilerDiagnostic({
    severity: 'Warning',
    whatHappened: notConfigured
      ? 'Locale twins found no translation files'
      : 'Locale twins could not find some translation files',
    why: notConfigured
      ? 'gt.config.json does not set files.gt.output'
      : undefined,
    reassurance: 'Those locales render the source text',
    fix: notConfigured
      ? 'Set files.gt.output in gt.config.json (for example "src/_gt/[locale].json") and run `gt translate` before `vite build`'
      : 'Run `gt translate` before `vite build`, or commit the translation files',
    details: missingFiles,
  });
}

/** A `[locale].json` file is not valid JSON. */
export function createInvalidTranslationFileDiagnostic(
  filePath: string,
  error: unknown
): string {
  return createCompilerDiagnostic({
    severity: 'Error',
    whatHappened: 'Locale twins could not read a translation file',
    why: 'it is not valid JSON',
    fix: 'Run `gt translate` again, or fix the file',
    details: errorDetails(filePath, error),
  });
}

/** The manifest of a previous build in the same output directory is unreadable. */
export function createUnreadablePreviousManifestDiagnostic(
  manifestPath: string,
  error: unknown
): string {
  return createCompilerDiagnostic({
    severity: 'Warning',
    whatHappened: 'Locale twins ignored the manifest of a previous build',
    reassurance:
      'The new twins are complete, but twins from that build are not cleaned up',
    fix: 'Empty the output directory before building (build.emptyOutDir)',
    details: errorDetails(manifestPath, error),
  });
}

/** Output files that are served as built still contain unfilled placeholders. */
export function createUnfilledPlaceholdersDiagnostic(
  fileNames: string[]
): string {
  return createCompilerDiagnostic({
    severity: 'Error',
    whatHappened:
      'The build output contains unfilled locale twin placeholders in files that are served as built',
    why: 'only twinned JS files get a twin per locale (the documents load the twins, never the originals), so these files would render empty text',
    fix: 'Keep translated modules in JS chunks; plugins must not copy compiled module code into other output files',
    details: fileNames,
  });
}

/** Most of the JS output is twinned, so it is copied once per locale. */
export function createLargeOutputMultiplierDiagnostic(input: {
  outputMultiplier: number;
  twinnedShare: number;
  vendorChunk: boolean;
}): string {
  return createCompilerDiagnostic({
    severity: 'Warning',
    whatHappened: `Locale twins multiply the JS output by ${input.outputMultiplier.toFixed(2)}`,
    why: `${Math.round(input.twinnedShare * 100)}% of the JS output is in twinned files, which are copied once per locale`,
    fix: input.vendorChunk
      ? 'Keep library code out of chunks that contain or import translated modules (the locale twins report lists twinned and shared files)'
      : 'Set localeTwins.vendorChunk to true (the default) so library code goes into a shared vendor chunk',
  });
}

/** The user configured chunking, so the default vendor chunk is not added. */
export function createVendorChunkSkippedDiagnostic(option: string): string {
  return createCompilerDiagnostic({
    severity: 'Warning',
    whatHappened: 'Locale twins did not add the default vendor chunk',
    why: `${option} is already configured`,
    reassurance: 'Your chunking config is used as is',
    fix: 'Keep library code (excluding modules that import the app) in its own chunk, so it is not copied once per locale',
    wayOut: 'set localeTwins.vendorChunk to false to silence this warning',
  });
}

/** `vite dev` serves no locale twins. */
export const LOCALE_TWINS_DEV_NOTICE = createCompilerDiagnostic({
  whatHappened: 'Locale twins are only generated by `vite build`',
  reassurance:
    'The dev server loads whole locales as usual and translates every entry, including entries that production builds render untranslated (the build warning lists them)',
  fix: 'Run `vite build && vite preview` to test locale twins locally',
});

/** Locale twins are generated by the Vite integration only. */
export function createLocaleTwinsUnsupportedBundlerDiagnostic(
  framework: string
): string {
  return createCompilerDiagnostic({
    severity: 'Warning',
    whatHappened: `Locale twins are on (splitting: "locale-twins"), but this ${framework} build cannot generate them`,
    why: 'locale twins are generated by the Vite plugin only, so this build writes no twins, and a browser runtime configured with "locale-twins" loads no translations',
    fix: 'Build with Vite, or set files.gt.splitting to "locale" (or remove it) in the config both the compiler and the runtime read',
  });
}

/** Locale twins need compile-time hashes to attribute entries to modules. */
export const LOCALE_TWINS_WITHOUT_COMPILE_TIME_HASH = createCompilerDiagnostic({
  severity: 'Warning',
  whatHappened: 'Locale twins are on, but compileTimeHash is off',
  why: 'no translation is attributed to a module without compile-time hashes, so the twins carry no translations',
  fix: 'Remove compileTimeHash: false from the compiler plugin options',
});

/** The server build needs the client build's twin manifest. */
export function createMissingLocaleTwinManifestDiagnostic(
  manifestPath: string
): string {
  return createCompilerDiagnostic({
    severity: 'Error',
    whatHappened: 'The locale twin manifest was not found',
    why: 'virtual:gt-locale-twins-manifest is read from the client build output, so the client environment must be built first',
    fix: 'Build the client environment before the server environment, and set environments.client.build.outDir if the client output is somewhere else',
    details: manifestPath,
  });
}

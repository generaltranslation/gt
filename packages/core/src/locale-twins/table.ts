import { formatDiagnosticErrorDetails } from '../logging/diagnostics';
import { createLocaleTwinDiagnostic } from './diagnostics';
import type { LocaleTwinEntries } from './placeholder';

/**
 * A filled locale twin value: one locale's content for a module's entries.
 * Short keys keep twins small: `l` is the locale, `e` maps hash to content.
 */
export type LocaleTwinTable = {
  l: string;
  e: LocaleTwinEntries;
};

// Pure: unused in apps without locale twins, so bundlers can drop them
const LINE_SEPARATOR = /* @__PURE__ */ String.fromCharCode(0x2028);
const PARAGRAPH_SEPARATOR = /* @__PURE__ */ String.fromCharCode(0x2029);

/**
 * Serializes a table into the JS source token that replaces a placeholder
 * literal (quotes included): `JSON.stringify(JSON.stringify(table))`, with
 * U+2028/U+2029 escaped so the literal is valid in every JS parser.
 *
 * At runtime the token evaluates to `JSON.stringify(table)`, which is what
 * {@link parseLocaleTwinTable} accepts.
 */
export function serializeLocaleTwinTable(table: LocaleTwinTable): string {
  return JSON.stringify(JSON.stringify(table))
    .split(LINE_SEPARATOR)
    .join('\\u2028')
    .split(PARAGRAPH_SEPARATOR)
    .join('\\u2029');
}

/**
 * Parses the runtime value of a filled placeholder (the string passed to the
 * registration call) into its table. Throws a diagnostic error when the value
 * is not a table, including when it is still an unfilled placeholder.
 */
export function parseLocaleTwinTable(value: string): LocaleTwinTable {
  let table: unknown;
  try {
    table = JSON.parse(value);
  } catch (error) {
    throw invalidTableError(error);
  }
  if (!isLocaleTwinTable(table)) throw invalidTableError();
  return table;
}

function isLocaleTwinTable(value: unknown): value is LocaleTwinTable {
  if (typeof value !== 'object' || value === null) return false;
  const { l, e } = value as Record<string, unknown>;
  return (
    typeof l === 'string' &&
    l.length > 0 &&
    typeof e === 'object' &&
    e !== null &&
    !Array.isArray(e)
  );
}

function invalidTableError(error?: unknown): Error {
  return new Error(
    createLocaleTwinDiagnostic({
      severity: 'Error',
      whatHappened: 'A locale twin table could not be read',
      why: 'the value is not a filled locale twin table',
      fix: 'Serve the locale twins generated by the build instead of the original chunks',
      details: formatDiagnosticErrorDetails(error),
    })
  );
}
